-- Execute este arquivo DEPOIS de criar as tabelas e inserir os dados
-- do arquivo 05-dml-consultas.sql.
--
-- Compatível com o esquema enviado:
-- tema.id_tema INTEGER
-- dificuldade.id_dificuldade INTEGER
-- alternativa.resposta INTEGER
-- jogador.id_tema INTEGER
--
-- Este script não recria tabelas nem apaga os dados do quiz.

BEGIN;

-- 1) Garante geração automática do ID do jogador.
-- A tabela original declara id_jogador como INTEGER PRIMARY KEY,
-- mas não define SERIAL/IDENTITY. A função de cadastro precisa de um ID.
DO $$
DECLARE
    v_identity text;
    v_default text;
BEGIN
    SELECT is_identity, column_default
      INTO v_identity, v_default
      FROM information_schema.columns
     WHERE table_schema = 'public'
       AND table_name = 'jogador'
       AND column_name = 'id_jogador';

    IF NOT FOUND THEN
        RAISE EXCEPTION 'A coluna public.jogador.id_jogador não foi encontrada.';
    END IF;

    IF v_identity = 'NO' AND v_default IS NULL THEN
        ALTER TABLE public.jogador
            ALTER COLUMN id_jogador ADD GENERATED BY DEFAULT AS IDENTITY;
    ELSIF v_identity = 'NO' AND v_default IS NOT NULL THEN
        -- Já existe um DEFAULT (por exemplo, SERIAL); mantém a configuração atual.
        NULL;
    END IF;
END
$$;

-- Sincroniza a sequência com os IDs já existentes, evitando colisão
-- caso o cadastro seja configurado depois de alguns registros.
DO $$
DECLARE
    v_sequence text;
BEGIN
    v_sequence := pg_get_serial_sequence('public.jogador', 'id_jogador');
    IF v_sequence IS NOT NULL THEN
        EXECUTE format(
            'SELECT setval(%L, COALESCE((SELECT MAX(id_jogador) FROM public.jogador), 0) + 1, false)',
            v_sequence
        );
    END IF;
END
$$;

-- 2) Ajusta a pergunta 16 para o tema correto (Erros da Computação).
UPDATE public.pergunta
   SET id_tema = 2
 WHERE id_pergunta = 16
   AND id_tema <> 2;

-- 3) Remove assinaturas antigas/incompatíveis para evitar sobrecarga ambígua.
DROP FUNCTION IF EXISTS public.paragon_obter_perguntas(VARCHAR);
DROP FUNCTION IF EXISTS public.paragon_obter_perguntas(INTEGER);

DROP FUNCTION IF EXISTS public.paragon_corrigir_resposta(INTEGER, NUMERIC);
DROP FUNCTION IF EXISTS public.paragon_corrigir_resposta(INTEGER, INTEGER);

DROP FUNCTION IF EXISTS public.paragon_registrar_jogador(VARCHAR, VARCHAR, NUMERIC);
DROP FUNCTION IF EXISTS public.paragon_registrar_jogador(VARCHAR, INTEGER, NUMERIC);

DROP FUNCTION IF EXISTS public.paragon_ranking();

-- 4) Busca até 10 perguntas aleatórias do tema.
-- Não retorna o gabarito nem a justificativa antes da resposta.
CREATE FUNCTION public.paragon_obter_perguntas(
    p_id_tema INTEGER
)
RETURNS TABLE (
    id_pergunta INTEGER,
    texto_pergunta TEXT,
    id_alternativa INTEGER,
    id_dificuldade INTEGER,
    nome_dificuldade VARCHAR(80),
    valor_pontos NUMERIC,
    alternativa_a TEXT,
    alternativa_b TEXT,
    alternativa_c TEXT,
    alternativa_d TEXT
)
LANGUAGE SQL
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
    SELECT
        p.id_pergunta,
        p.texto_pergunta,
        a.id_alternativa,
        d.id_dificuldade,
        d.nome_dificuldade,
        d.valor_pontos,
        a.alternativa_a,
        a.alternativa_b,
        a.alternativa_c,
        a.alternativa_d
    FROM public.pergunta AS p
    INNER JOIN public.alternativa AS a
        ON a.id_alternativa = p.id_alternativa
    INNER JOIN public.dificuldade AS d
        ON d.id_dificuldade = p.id_dificuldade
    WHERE p.id_tema = p_id_tema
    ORDER BY random()
    LIMIT 10;
$$;

-- 5) Corrige uma resposta e devolve resultado, gabarito e justificativa.
CREATE FUNCTION public.paragon_corrigir_resposta(
    p_id_alternativa INTEGER,
    p_resposta_marcada INTEGER
)
RETURNS TABLE (
    correto BOOLEAN,
    resposta_correta INTEGER,
    justificativa TEXT,
    valor_pontos NUMERIC
)
LANGUAGE SQL
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
    SELECT
        (a.resposta = p_resposta_marcada) AS correto,
        a.resposta AS resposta_correta,
        a.justificativa,
        COALESCE(d.valor_pontos, 0) AS valor_pontos
    FROM public.alternativa AS a
    INNER JOIN public.pergunta AS p
        ON p.id_alternativa = a.id_alternativa
    INNER JOIN public.dificuldade AS d
        ON d.id_dificuldade = p.id_dificuldade
    WHERE a.id_alternativa = p_id_alternativa
    LIMIT 1;
$$;

-- 6) Registra a pontuação final do jogador e retorna seu ID.
CREATE FUNCTION public.paragon_registrar_jogador(
    p_nome VARCHAR,
    p_id_tema INTEGER,
    p_pontos NUMERIC
)
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_novo_id INTEGER;
BEGIN
    IF p_nome IS NULL OR length(trim(p_nome)) = 0 THEN
        RAISE EXCEPTION 'Informe um nome para o jogador.';
    END IF;

    IF p_id_tema IS NULL THEN
        RAISE EXCEPTION 'Selecione um tema para o quiz.';
    END IF;

    IF p_pontos IS NULL OR p_pontos < 0 THEN
        RAISE EXCEPTION 'A pontuação não pode ser negativa ou nula.';
    END IF;

    INSERT INTO public.jogador (nome, rank, pontos, id_tema)
    VALUES (left(trim(p_nome), 80), 0, p_pontos, p_id_tema)
    RETURNING id_jogador INTO v_novo_id;

    RETURN v_novo_id;
END;
$$;

-- 7) Retorna os dez melhores resultados.
CREATE FUNCTION public.paragon_ranking()
RETURNS TABLE (
    nome VARCHAR(80),
    pontos NUMERIC
)
LANGUAGE SQL
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
    SELECT j.nome, j.pontos
    FROM public.jogador AS j
    ORDER BY j.pontos DESC, j.nome ASC
    LIMIT 10;
$$;

-- 8) Permissões: somente as funções utilizadas pelo frontend.
REVOKE ALL ON FUNCTION public.paragon_obter_perguntas(INTEGER) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.paragon_corrigir_resposta(INTEGER, INTEGER) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.paragon_registrar_jogador(VARCHAR, INTEGER, NUMERIC) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.paragon_ranking() FROM PUBLIC;

GRANT EXECUTE ON FUNCTION public.paragon_obter_perguntas(INTEGER) TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.paragon_corrigir_resposta(INTEGER, INTEGER) TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.paragon_registrar_jogador(VARCHAR, INTEGER, NUMERIC) TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.paragon_ranking() TO anon, authenticated;

COMMIT;

